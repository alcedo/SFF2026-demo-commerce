export async function neonCreateOrder(input: {
  id: string;
  productId: number;
  quantity: number;
  buyerAddress?: string;
  amountMicro: number;
  createdAt: string;
  derivationIndex: number;
}): Promise<Order> {
  await ensureNeonShop();
  try {
    const rows = await getSql()`
      SELECT * FROM reserve_shop_order(
        ${input.id},
        ${input.productId},
        ${input.quantity},
        ${input.buyerAddress ?? null},
        ${input.amountMicro},
        ${input.createdAt}::timestamptz,
        ${input.derivationIndex}
      )
    `;
    const row = rows[0] as Record<string, unknown> | undefined;
    if (!row) throw new Error("Could not create order");
    return asOrder(row);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    if (message.includes("Not enough vouchers in stock")) {
      throw new Error("Not enough vouchers in stock");
    }
    throw error;
  }
}

