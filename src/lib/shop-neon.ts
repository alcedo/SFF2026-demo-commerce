export async function neonAddVouchers(
  productId: number,
  codes: string[]
): Promise<void> {
  await ensureNeonShop();
  const sql = getSql();
  const product = await neonGetProduct(productId);
  if (!product) throw new Error("Product not found");
  const now = new Date().toISOString();
  for (const raw of codes) {
    const code = raw.trim();
    if (!code) continue;
    try {
      await sql`
        INSERT INTO vouchers (product_id, code, status, created_at)
        VALUES (${productId}, ${code}, 'available', ${now})
      `;
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      if (message.includes("vouchers_code") || message.includes("duplicate")) {
        throw new Error(`Code already exists: ${code}`);
      }
      throw error;
    }
  }
}

export async function neonListVouchers(filter?: {
  status?: string;
  query?: string;
}): Promise<VoucherRow[]> {
  await ensureNeonShop();
  const rows = await getSql()`
    SELECT
      v.*,
      p.name AS product_name,
      p.brand,
      p.usd_value,
      o.tx_hash,
      o.status AS order_status
    FROM vouchers v
    JOIN products p ON p.id = v.product_id
    LEFT JOIN orders o ON o.id = v.order_id
    ORDER BY v.id DESC
  `;
  return rows
    .map((row) => asVoucherRow(row as Record<string, unknown>))
    .filter((voucher) => {
      if (
        filter?.status &&
        filter.status !== "all" &&
        voucher.status !== filter.status
      ) {
        return false;
      }
      if (filter?.query) {
        const hay =
          `${voucher.code} ${voucher.product_name} ${voucher.brand} ${voucher.order_id ?? ""}`.toLowerCase();
        if (!hay.includes(filter.query.toLowerCase())) return false;
      }
      return true;
    });
}

export async function neonVoucherStats() {
  await ensureNeonShop();
  const rows = await getSql()`
    SELECT
      COUNT(*)::int AS total,
      COUNT(*) FILTER (WHERE status = 'available')::int AS available,
      COUNT(*) FILTER (WHERE status = 'used')::int AS used,
      COUNT(*) FILTER (WHERE status = 'expired')::int AS expired
    FROM vouchers
  `;
  const row = rows[0] as {
    total: number;
    available: number;
    used: number;
    expired: number;
  };
  return {
    total: Number(row.total),
    available: Number(row.available),
    used: Number(row.used),
    expired: Number(row.expired),
  };
}

export async function neonListRecentActivity(limit = 8): Promise<VoucherRow[]> {
  const rows = await neonListVouchers();
  return rows
    .filter((voucher) => ["sold", "used", "reserved"].includes(voucher.status))
    .sort((left, right) => {
      const leftAt = left.used_at ?? left.sold_at ?? left.created_at;
      const rightAt = right.used_at ?? right.sold_at ?? right.created_at;
      return rightAt.localeCompare(leftAt);
    })
    .slice(0, limit);
}

