function toIso(value: unknown): string {
  if (value instanceof Date) return value.toISOString();
  const raw = String(value);
  if (raw.includes("T")) return new Date(raw).toISOString();
  return new Date(`${raw.replace(" ", "T")}Z`).toISOString();
}

function asProduct(row: Record<string, unknown>): Product {
  return {
    id: Number(row.id),
    slug: String(row.slug),
    brand: String(row.brand),
    name: String(row.name),
    description: String(row.description),
    category: String(row.category),
    usd_value: Number(row.usd_value),
    price_micro: Number(row.price_micro),
    theme: String(row.theme),
    active: Number(row.active),
    created_at: toIso(row.created_at),
  };
}

function asOrder(row: Record<string, unknown>): Order {
  return {
    id: String(row.id),
    product_id: Number(row.product_id),
    quantity: Number(row.quantity),
    buyer_address: row.buyer_address == null ? null : String(row.buyer_address),
    amount_micro: Number(row.amount_micro),
    derivation_index: Number(row.derivation_index),
    tx_hash: row.tx_hash == null ? null : String(row.tx_hash),
    status: row.status as Order["status"],
    created_at: toIso(row.created_at),
    paid_at: row.paid_at == null ? null : toIso(row.paid_at),
  };
}

function asVoucher(row: Record<string, unknown>): Voucher {
  return {
    id: Number(row.id),
    product_id: Number(row.product_id),
    code: String(row.code),
    status: row.status as VoucherStatus,
    order_id: row.order_id == null ? null : String(row.order_id),
    sold_at: row.sold_at == null ? null : toIso(row.sold_at),
    used_at: row.used_at == null ? null : toIso(row.used_at),
    created_at: toIso(row.created_at),
  };
}

function asVoucherRow(row: Record<string, unknown>): VoucherRow {
  return {
    ...asVoucher(row),
    product_name: String(row.product_name ?? ""),
    brand: String(row.brand ?? ""),
    usd_value: Number(row.usd_value ?? 0),
    tx_hash: row.tx_hash == null ? null : String(row.tx_hash),
    order_status: row.order_status == null ? null : String(row.order_status),
  };
}

const DDL = [
  `CREATE TABLE IF NOT EXISTS products (
    id INTEGER PRIMARY KEY,
    slug TEXT UNIQUE NOT NULL,
    brand TEXT NOT NULL,
    name TEXT NOT NULL,
    description TEXT NOT NULL,
    category TEXT NOT NULL,
    usd_value DOUBLE PRECISION NOT NULL,
    price_micro BIGINT NOT NULL,
    theme TEXT NOT NULL,
    active INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
  )`,
  `CREATE TABLE IF NOT EXISTS orders (
    id TEXT PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES products(id),
    quantity INTEGER NOT NULL,
    buyer_address TEXT,
    amount_micro BIGINT NOT NULL,
    derivation_index INTEGER NOT NULL,
    tx_hash TEXT UNIQUE,
    status TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    paid_at TIMESTAMPTZ
  )`,
  `CREATE TABLE IF NOT EXISTS vouchers (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    product_id INTEGER NOT NULL REFERENCES products(id),
    code TEXT UNIQUE NOT NULL,
    status TEXT NOT NULL,
    order_id TEXT REFERENCES orders(id),
    sold_at TIMESTAMPTZ,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
  )`,
  `CREATE INDEX IF NOT EXISTS vouchers_product_status_idx ON vouchers (product_id, status)`,
  `CREATE INDEX IF NOT EXISTS orders_status_idx ON orders (status)`,
  `CREATE UNIQUE INDEX IF NOT EXISTS orders_live_hd_idx
     ON orders (derivation_index)
     WHERE status IN ('pending', 'paid')`,
  `CREATE OR REPLACE FUNCTION reserve_shop_order(
     p_id TEXT,
     p_product_id INTEGER,
     p_quantity INTEGER,
     p_buyer TEXT,
     p_amount BIGINT,
     p_created TIMESTAMPTZ,
     p_index INTEGER
   ) RETURNS SETOF orders
   LANGUAGE plpgsql AS $$
   DECLARE
     v_reserved INTEGER;
   BEGIN
     INSERT INTO orders (
       id, product_id, quantity, buyer_address, amount_micro,
       derivation_index, tx_hash, status, created_at, paid_at
     ) VALUES (
       p_id, p_product_id, p_quantity, p_buyer, p_amount,
       p_index, NULL, 'pending', p_created, NULL
     );

     UPDATE vouchers
        SET status = 'reserved', order_id = p_id
      WHERE id IN (
        SELECT id
          FROM vouchers
         WHERE product_id = p_product_id
           AND status = 'available'
         ORDER BY id
         FOR UPDATE SKIP LOCKED
         LIMIT p_quantity
      );
     GET DIAGNOSTICS v_reserved = ROW_COUNT;
     IF v_reserved < p_quantity THEN
       RAISE EXCEPTION 'Not enough vouchers in stock';
     END IF;

     RETURN QUERY SELECT * FROM orders WHERE id = p_id;
   END;
   $$`,
];

async function applySchema() {
  const sql = getSql();
  for (const statement of DDL) {
    await sql.query(statement);
  }
}

async function seedIfEmpty() {
  const sql = getSql();
  const now = new Date().toISOString();
  for (const [index, item] of CATALOG.entries()) {
    const id = index + 1;
    const usd_value = fromMicroUsdc(toMicroUsdc(item.usdValue));
    const price_micro = Number(toMicroUsdc(item.usdValue));
    await sql`
      INSERT INTO products (
        id, slug, brand, name, description, category,
        usd_value, price_micro, theme, active, created_at
      ) VALUES (
        ${id}, ${item.slug}, ${item.brand}, ${item.name}, ${item.description},
        ${item.category}, ${usd_value}, ${price_micro}, ${item.theme}, 1, ${now}
      )
      ON CONFLICT (slug) DO UPDATE SET
        brand = EXCLUDED.brand,
        name = EXCLUDED.name,
        description = EXCLUDED.description,
        category = EXCLUDED.category,
        usd_value = EXCLUDED.usd_value,
        price_micro = EXCLUDED.price_micro,
        theme = EXCLUDED.theme
    `;
  }

  const [{ count }] = (await sql`SELECT COUNT(*)::int AS count FROM vouchers`) as {
    count: number;
  }[];
  if (count > 0) return;

  const products = (await sql`SELECT id, slug FROM products ORDER BY id`) as {
    id: number;
    slug: string;
  }[];
  let nextId = 1;
  for (const product of products) {
    for (let i = 0; i < 12; i += 1) {
      await sql`
        INSERT INTO vouchers (id, product_id, code, status, created_at)
        VALUES (
          ${nextId}, ${product.id}, ${voucherCode(`${product.slug}:${i}`)},
          'available', ${now}
        )
      `;
      nextId += 1;
    }
  }
  const amazon = products.find((product) => product.slug === "amazon");
  const netflix = products.find((product) => product.slug === "netflix");
  if (amazon) {
    await sql`
      INSERT INTO vouchers (
        id, product_id, code, status, sold_at, used_at, created_at
      ) VALUES (
        ${nextId}, ${amazon.id}, ${voucherCode("amazon:used")},
        'used', ${now}, ${now}, ${now}
      )
    `;
    nextId += 1;
  }
  if (netflix) {
    await sql`
      INSERT INTO vouchers (id, product_id, code, status, created_at)
      VALUES (
        ${nextId}, ${netflix.id}, ${voucherCode("netflix:expired")},
        'expired', ${now}
      )
    `;
  }
  await sql.query(
    `SELECT setval(pg_get_serial_sequence('vouchers', 'id'), (SELECT COALESCE(MAX(id), 1) FROM vouchers))`
  );
}

export async function ensureNeonShop() {
  if (!globalForNeonShop.__voucherShopNeonReady) {
    globalForNeonShop.__voucherShopNeonReady = (async () => {
      await applySchema();
      await seedIfEmpty();
    })().catch((error) => {
      globalForNeonShop.__voucherShopNeonReady = undefined;
      throw error;
    });
  }
  await globalForNeonShop.__voucherShopNeonReady;
}

